function fileToGenerativePart(path, mimeType) {
  return {
    inlineData: {
      data: Buffer.from(fs.readFileSync(path)).toString("base64"),
      mimeType
    },
  };
}

app.post('/api/diagnose', upload.array('images', 5), async (req, res) => {
    try {
        if (!req.files || req.files.length === 0) {
            return res.status(400).json({ error: "画像がアップロードされていません" });
        }

        const imageParts = req.files.map(file => 
            fileToGenerativePart(file.path, file.mimetype)
        );

        const model = genAI.getGenerativeModel({ model: "gemini-1.5-flash" });
        const result = await model.generateContent([SYSTEM_PROMPT, ...imageParts]);
        const responseText = result.response.text();


        req.files.forEach(file => fs.unlinkSync(file.path));

        res.json({ result: responseText });

    } catch (error) {
        console.error(error);
        res.status(500).json({ error: "診断中にエラーが発生しました" });
    }
});

